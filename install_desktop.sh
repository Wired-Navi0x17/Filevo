#!/usr/bin/env bash
#
# Sortwise desktop installer — makes the app appear in the KDE application menu.
#
#   ./install_desktop.sh              # install for the current user
#   ./install_desktop.sh --uninstall  # remove the launcher, icon and menu entry
#   ./install_desktop.sh --dry-run    # show what would happen
#
# Everything is written under $HOME ($XDG_DATA_HOME), i.e. no root required and
# nothing system-wide is touched.  Set SORTWISE_INSTALL_ROOT to redirect the
# install into a sandbox (used by the test suite).
#
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

# ── argument parsing ────────────────────────────────────────────────────────
MODE="install"
for arg in "$@"; do
  case "$arg" in
    --uninstall) MODE="uninstall" ;;
    --dry-run)   MODE="dry-run" ;;
    -h|--help)
      sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *)
      echo "Unknown option: $arg" >&2
      exit 2 ;;
  esac
done

# ── paths ───────────────────────────────────────────────────────────────────
HOME_DIR="${SORTWISE_INSTALL_ROOT:-$HOME}"
DATA_HOME="${XDG_DATA_HOME:-$HOME_DIR/.local/share}"
APPS_DIR="$DATA_HOME/applications"
ICON_DIR="$DATA_HOME/icons/hicolor/scalable/apps"
BIN_DIR="$HOME_DIR/.local/bin"

DESKTOP_FILE="$APPS_DIR/sortwise.desktop"
ICON_FILE="$ICON_DIR/sortwise.svg"
LAUNCHER="$BIN_DIR/sortwise"

say() { printf '  %s\n' "$*"; }

# ── interpreter discovery ───────────────────────────────────────────────────
discover_python() {
  local candidates=(
    "$SCRIPT_DIR/.venv/bin/python"
    "$SCRIPT_DIR/.venv/bin/python3"
  )
  for candidate in "${candidates[@]}"; do
    if [[ -x "$candidate" ]]; then
      printf '%s' "$candidate"
      return 0
    fi
  done
  if command -v python3 >/dev/null 2>&1; then
    command -v python3
    return 0
  fi
  printf 'python3'
}

PYTHON="$(discover_python)"

# ── uninstall ───────────────────────────────────────────────────────────────
if [[ "$MODE" == "uninstall" ]]; then
  echo "Uninstalling Sortwise desktop integration…"
  for target in "$DESKTOP_FILE" "$ICON_FILE" "$LAUNCHER"; do
    if [[ -e "$target" ]]; then
      rm -f -- "$target"
      say "removed $target"
    fi
  done
  command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$APPS_DIR" 2>/dev/null || true
  echo "Done."
  exit 0
fi

# ── icon ────────────────────────────────────────────────────────────────────
read -r -d '' ICON_SVG <<'SVG' || true
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" role="img" aria-label="Sortwise">
  <rect x="4" y="4" width="120" height="120" rx="16" fill="#181a1f" stroke="#2c2e38" stroke-width="2"/>
  <!-- Concentric Filelight ring arcs -->
  <circle cx="64" cy="64" r="16" fill="#202228" stroke="#3b82f6" stroke-width="2"/>
  <path d="M64 36 A28 28 0 0 1 92 64" fill="none" stroke="#9aa1b2" stroke-width="6"/>
  <path d="M92 64 A28 28 0 0 1 64 92" fill="none" stroke="#3b82f6" stroke-width="6"/>
  <path d="M64 92 A28 28 0 0 1 36 64" fill="none" stroke="#2c2e38" stroke-width="6"/>
  <path d="M36 64 A28 28 0 0 1 64 36" fill="none" stroke="#4b5266" stroke-width="6"/>
  <!-- Outer ring arcs -->
  <path d="M64 20 A44 44 0 0 1 108 64" fill="none" stroke="#3b82f6" stroke-width="4"/>
  <path d="M108 64 A44 44 0 0 1 64 108" fill="none" stroke="#9aa1b2" stroke-width="4"/>
  <path d="M64 108 A44 44 0 0 1 20 64" fill="none" stroke="#4b5266" stroke-width="4"/>
  <!-- Center dot -->
  <circle cx="64" cy="64" r="5" fill="#f0f2f5"/>
</svg>
SVG

LAUNCHER_BODY="#!/usr/bin/env bash
# Generated by install_desktop.sh — launches Sortwise native desktop application.
_nix_lib=\"/run/current-system/sw/share/nix-ld/lib\"
if [[ -d \"\$_nix_lib\" ]]; then
  if [[ -z \"\${LD_LIBRARY_PATH:-}\" ]]; then
    export LD_LIBRARY_PATH=\"\$_nix_lib\"
  elif [[ \":\$LD_LIBRARY_PATH:\" != *\":\$_nix_lib:\"* ]]; then
    export LD_LIBRARY_PATH=\"\$_nix_lib:\$LD_LIBRARY_PATH\"
  fi
fi
exec \"$PYTHON\" \"$SCRIPT_DIR/src/native_app.py\" \"\$@\"
"

DESKTOP_BODY="[Desktop Entry]
Type=Application
Version=1.0
Name=Sortwise
GenericName=Document Router
Comment=Native desktop calibrated document router and Filelight storage visualizer
Exec=$LAUNCHER
Icon=sortwise
Terminal=false
Categories=Utility;Office;FileTools;
Keywords=sort;route;documents;pdf;docx;pptx;study;ai;machine-learning;filelight;
StartupNotify=true
StartupWMClass=Sortwise
Path=$SCRIPT_DIR
"

if [[ "$MODE" == "dry-run" ]]; then
  echo "Sortwise install preview (dry run):"
  say "interpreter : $PYTHON"
  say "launcher    : $LAUNCHER"
  say "icon        : $ICON_FILE"
  say "menu entry  : $DESKTOP_FILE"
  exit 0
fi

echo "Installing Sortwise desktop integration…"
say "project root : $SCRIPT_DIR"
say "interpreter  : $PYTHON"

mkdir -p "$APPS_DIR" "$ICON_DIR" "$BIN_DIR"

printf '%s' "$ICON_SVG" > "$ICON_FILE"
say "wrote icon       $ICON_FILE"

printf '%s' "$LAUNCHER_BODY" > "$LAUNCHER"
chmod 0755 "$LAUNCHER"
say "wrote launcher   $LAUNCHER"

printf '%s' "$DESKTOP_BODY" > "$DESKTOP_FILE"
chmod 0644 "$DESKTOP_FILE"
say "wrote menu entry $DESKTOP_FILE"

# refresh the caches so the entry shows up without a re-login (best effort)
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$APPS_DIR" 2>/dev/null || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1 && [[ -d "$DATA_HOME/icons/hicolor" ]]; then
  gtk-update-icon-cache -q -t -f "$DATA_HOME/icons/hicolor" 2>/dev/null || true
fi
if command -v kbuildsycoca6 >/dev/null 2>&1; then
  kbuildsycoca6 --noincremental >/dev/null 2>&1 || true
elif command -v kbuildsycoca5 >/dev/null 2>&1; then
  kbuildsycoca5 --noincremental >/dev/null 2>&1 || true
fi

echo "Installed. Launch it from the application menu (search 'Sortwise'),"
echo "or run:  $LAUNCHER"
echo
echo "It opens a real, physical native desktop window (CustomTkinter + Tk canvas)"
echo "directly on your Wayland/X11 display with zero browser or webview dependencies."
