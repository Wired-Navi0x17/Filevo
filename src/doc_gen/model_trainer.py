"""Supervised Fine-Tuning and Adaptation Pipeline for Filevo.

Trains or fine-tunes local language models on the leakage-free supervision
datasets generated by DocxDatasetBuilder. Supports GPU acceleration on CUDA,
graceful CPU fallback, token loss masking, evaluation steps, and checkpoint saving.
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any


@dataclass
class TrainingMetrics:
    """Metrics recorded during a training run."""
    epochs: int
    train_loss: float
    eval_loss: float
    steps_completed: int
    samples_trained: int
    eval_samples: int
    device: str
    checkpoint_dir: str


class FilevoModelTrainer:
    """Supervised fine-tuning pipeline for Filevo document intelligence."""

    def __init__(
        self,
        model_id: str | None = None,
        dataset_dir: str | Path | None = None,
        output_dir: str | Path | None = None,
        learning_rate: float = 5e-5,
        epochs: int = 2,
        batch_size: int = 2,
    ):
        self.model_id = model_id or os.environ.get("FILEVO_MODEL_ID", "HuggingFaceTB/SmolLM2-1.7B-Instruct")
        self.dataset_dir = (
            Path(dataset_dir) if dataset_dir else Path.home() / ".filevo" / "datasets"
        )
        self.output_dir = (
            Path(output_dir) if output_dir else Path.home() / ".filevo" / "checkpoints" / "filevo-adapted"
        )
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.learning_rate = learning_rate
        self.epochs = epochs
        self.batch_size = batch_size

    def load_dataset_records(self) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
        """Load train and eval JSONL datasets."""
        train_file = self.dataset_dir / "docx_supervision_train.jsonl"
        eval_file = self.dataset_dir / "docx_supervision_eval.jsonl"

        train_records = []
        if train_file.exists():
            with open(train_file, "r", encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        train_records.append(json.loads(line))

        eval_records = []
        if eval_file.exists():
            with open(eval_file, "r", encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        eval_records.append(json.loads(line))

        return train_records, eval_records

    @staticmethod
    def format_sample(record: dict[str, Any]) -> tuple[str, str]:
        """Format an example into prompt and completion text."""
        instruction = record.get("instruction", "")
        context = record.get("input_context", "")
        target = record.get("target_content", "")
        if not target and record.get("target_outline"):
            target = "\n".join(f"- {h}" for h in record["target_outline"])

        prompt = f"<|im_start|>user\n{instruction}"
        if context:
            prompt += f"\nContext: {context}"
        prompt += "<|im_end|>\n<|im_start|>assistant\n"

        completion = f"{target}<|im_end|>\n"
        return prompt, completion

    def train(self, dry_run: bool = False, max_steps: int | None = None) -> TrainingMetrics:
        """Run fine-tuning or adaptation loop."""
        train_records, eval_records = self.load_dataset_records()

        if not train_records:
            raise ValueError(
                f"No training data found in {self.dataset_dir}. "
                "Run 'report index' or generate a dataset first via DocxDatasetBuilder."
            )

        if dry_run:
            # Validate dataset format and simulate step metrics without GPU allocation
            return TrainingMetrics(
                epochs=self.epochs,
                train_loss=0.421,
                eval_loss=0.435,
                steps_completed=len(train_records),
                samples_trained=len(train_records),
                eval_samples=len(eval_records),
                device="dry_run",
                checkpoint_dir=str(self.output_dir),
            )

        try:
            import torch
            from transformers import AutoModelForCausalLM, AutoTokenizer
        except ImportError as e:
            raise RuntimeError(f"Missing required ML libraries for fine-tuning: {e}")

        device = "cuda" if torch.cuda.is_available() else "cpu"
        dtype = torch.bfloat16 if torch.cuda.is_available() and torch.cuda.is_bf16_supported() else (
            torch.float16 if torch.cuda.is_available() else torch.float32
        )

        tokenizer = AutoTokenizer.from_pretrained(self.model_id)
        if tokenizer.pad_token is None:
            tokenizer.pad_token = tokenizer.eos_token

        model = AutoModelForCausalLM.from_pretrained(
            self.model_id,
            torch_dtype=dtype,
            device_map="auto" if device == "cuda" else None,
        )
        if device == "cpu":
            model.to(device)

        model.train()
        optimizer = torch.optim.AdamW(model.parameters(), lr=self.learning_rate)

        # Prepare tokenized batches with target loss masking
        processed_train = []
        for rec in train_records:
            prompt, completion = self.format_sample(rec)
            prompt_ids = tokenizer.encode(prompt, add_special_tokens=False)
            comp_ids = tokenizer.encode(completion, add_special_tokens=False)

            input_ids = prompt_ids + comp_ids
            # Mask prompt tokens with -100 so loss is computed solely on the assistant response
            labels = [-100] * len(prompt_ids) + comp_ids

            if len(input_ids) > 1024:
                input_ids = input_ids[:1024]
                labels = labels[:1024]

            processed_train.append((input_ids, labels))

        total_steps = 0
        total_loss = 0.0

        for epoch in range(1, self.epochs + 1):
            for i in range(0, len(processed_train), self.batch_size):
                if max_steps and total_steps >= max_steps:
                    break

                batch = processed_train[i : i + self.batch_size]
                max_len = max(len(x[0]) for x in batch)

                b_input_ids = []
                b_labels = []
                b_attn = []

                for inp, lbl in batch:
                    pad_len = max_len - len(inp)
                    b_input_ids.append(inp + [tokenizer.pad_token_id] * pad_len)
                    b_labels.append(lbl + [-100] * pad_len)
                    b_attn.append([1] * len(inp) + [0] * pad_len)

                t_input = torch.tensor(b_input_ids, dtype=torch.long, device=model.device)
                t_labels = torch.tensor(b_labels, dtype=torch.long, device=model.device)
                t_attn = torch.tensor(b_attn, dtype=torch.long, device=model.device)

                optimizer.zero_grad()
                outputs = model(input_ids=t_input, attention_mask=t_attn, labels=t_labels)
                loss = outputs.loss
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                optimizer.step()

                total_loss += loss.item()
                total_steps += 1

        avg_train_loss = total_loss / max(total_steps, 1)

        # Evaluation pass
        model.eval()
        eval_loss = 0.0
        eval_steps = 0
        with torch.no_grad():
            for rec in eval_records:
                prompt, completion = self.format_sample(rec)
                p_ids = tokenizer.encode(prompt, add_special_tokens=False)
                c_ids = tokenizer.encode(completion, add_special_tokens=False)
                inp = torch.tensor([p_ids + c_ids], dtype=torch.long, device=model.device)
                lbl = torch.tensor([[-100] * len(p_ids) + c_ids], dtype=torch.long, device=model.device)
                if inp.size(1) > 1024:
                    inp = inp[:, :1024]
                    lbl = lbl[:, :1024]
                out = model(input_ids=inp, labels=lbl)
                eval_loss += out.loss.item()
                eval_steps += 1

        avg_eval_loss = eval_loss / max(eval_steps, 1) if eval_steps > 0 else avg_train_loss

        # Save adapted weights and tokenizer
        model.save_pretrained(self.output_dir)
        tokenizer.save_pretrained(self.output_dir)

        # Write training report
        metrics = TrainingMetrics(
            epochs=self.epochs,
            train_loss=round(avg_train_loss, 4),
            eval_loss=round(avg_eval_loss, 4),
            steps_completed=total_steps,
            samples_trained=len(train_records),
            eval_samples=len(eval_records),
            device=device,
            checkpoint_dir=str(self.output_dir),
        )

        with open(self.output_dir / "training_metrics.json", "w", encoding="utf-8") as f:
            json.dump(metrics.__dict__, f, indent=2)

        return metrics
