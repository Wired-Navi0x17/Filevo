def is_research_paper_request(prompt: str) -> bool:
    """Detect if the user is requesting an academic research paper or scholarly report."""
    from src.interpreter import get_request_interpreter
    spec = get_request_interpreter().interpret(prompt)
    return spec.action == "create_document" and spec.deliverable_type in ("research_paper", "literature_review", "technical_report")


def extract_topic_from_prompt(prompt: str) -> str:
    """Extract clean domain topic from natural language document request."""
    from src.interpreter import get_request_interpreter
    return get_request_interpreter().extract_subject(prompt)


